/** 시도·시군구의 대표 좌표. 없으면 null */
export function getCoord(sido: string, sigungu: string): LngLat | null {
  return COORDS_BY_SIDO[sido]?.[sigungu] ?? null;
}

/** 목록(SIGUNGU)에 있는데 좌표가 없는 시·군·구 (테스트용) */
export function missingCoords(): string[] {
  const missing: string[] = [];
  for (const [sido, list] of Object.entries(SIGUNGU)) {
    for (const g of list) if (!getCoord(sido, g)) missing.push(`${sido} ${g}`);
  }
  return missing;
}
